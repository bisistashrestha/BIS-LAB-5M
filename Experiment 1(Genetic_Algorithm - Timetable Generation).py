import random
import numpy as np
import pandas as pd

# Configure for a single day with 8 periods and 3 rooms
CLASSES = ['Grade 10', 'Grade 11', 'Grade 12']
SUBJECTS = ['Math', 'Science', 'English', 'History', 'Art', 'Music', 'Geography', 'Physical Ed']
TEACHERS = ['Alice', 'Bob', 'Charlie', 'Diana', 'Evan', 'Fiona']
ROOMS = ['Room A', 'Room B', 'Room C']
DAYS = ['Monday']
PERIODS = [f'Period {i}' for i in range(1, 9)]
NUM_SLOTS = len(DAYS) * len(PERIODS)

TEACHER_SUBJECTS = {
    'Math': ['Alice', 'Bob'],
    'Science': ['Bob', 'Charlie'],
    'English': ['Charlie', 'Diana'],
    'History': ['Diana', 'Evan'],
    'Art': ['Diana', 'Fiona'],
    'Music': ['Alice', 'Fiona'],
    'Geography': ['Evan', 'Fiona'],
    'Physical Ed': ['Evan', 'Bob']
}

class SingleDaySchedule:
    def __init__(self):
        # Gene structure: (period, room) -> (class, subject, teacher) or None
        self.genes = {}
        self.fitness = 0.0

    def initialize_random(self):
        for period in PERIODS:
            # Shuffle classes so each class can get placed in one of the 3 rooms randomly
            shuffled_classes = list(CLASSES) + [None] * (len(ROOMS) - len(CLASSES))
            random.shuffle(shuffled_classes)

            for room_idx, room in enumerate(ROOMS):
                klass = shuffled_classes[room_idx]
                if klass is not None:
                    subject = random.choice(SUBJECTS)
                    teacher = random.choice(TEACHER_SUBJECTS[subject])
                    self.genes[(period, room)] = (klass, subject, teacher)
                else:
                    self.genes[(period, room)] = None

    def calculate_fitness(self):
        penalties = 0

        for period in PERIODS:
            teachers_active = []
            classes_active = []

            for room in ROOMS:
                assignment = self.genes.get((period, room))
                if assignment is not None:
                    klass, subject, teacher = assignment
                    teachers_active.append(teacher)
                    classes_active.append(klass)

            # Constraint 1: Teacher conflict (same teacher scheduled in multiple rooms at the same time)
            teacher_conflicts = len(teachers_active) - len(set(teachers_active))
            penalties += teacher_conflicts * 50

            # Constraint 2: Class conflict (same class scheduled in multiple rooms at the same time)
            class_conflicts = len(classes_active) - len(set(classes_active))
            penalties += class_conflicts * 50

        # Constraint 3: Balanced distribution of subjects per class over the single day
        for klass in CLASSES:
            subject_counts = {}
            for (period, room), val in self.genes.items():
                if val is not None and val[0] == klass:
                    subject = val[1]
                    subject_counts[subject] = subject_counts.get(subject, 0) + 1

            counts = list(subject_counts.values())
            variance = np.var(counts) if counts else 0
            penalties += variance * 2

        self.fitness = 1.0 / (1.0 + penalties)
        return self.fitness

def crossover(parent1, parent2):
    child = SingleDaySchedule()
    crossover_point = random.randint(0, len(PERIODS) - 1)

    for period_idx, period in enumerate(PERIODS):
        for room in ROOMS:
            if period_idx < crossover_point:
                child.genes[(period, room)] = parent1.genes[(period, room)]
            else:
                child.genes[(period, room)] = parent2.genes[(period, room)]
    return child

def mutate(schedule, mutation_rate=0.15):
    for period in PERIODS:
        if random.random() < mutation_rate:
            shuffled_classes = list(CLASSES) + [None] * (len(ROOMS) - len(CLASSES))
            random.shuffle(shuffled_classes)

            for room_idx, room in enumerate(ROOMS):
                klass = shuffled_classes[room_idx]
                if klass is not None:
                    subject = random.choice(SUBJECTS)
                    teacher = random.choice(TEACHER_SUBJECTS[subject])
                    schedule.genes[(period, room)] = (klass, subject, teacher)
                else:
                    schedule.genes[(period, room)] = None

def run_single_day_ga(pop_size=100, generations=200, mutation_rate=0.15):
    population = []
    for _ in range(pop_size):
        sched = SingleDaySchedule()
        sched.initialize_random()
        sched.calculate_fitness()
        population.append(sched)

    for gen in range(generations):
        population.sort(key=lambda x: x.fitness, reverse=True)

        if population[0].fitness == 1.0:
            print(f"Fully optimized conflict-free schedule found at Generation {gen}!")
            break

        new_pop = population[:15]

        while len(new_pop) < pop_size:
            p1 = max(random.sample(population, 5), key=lambda x: x.fitness)
            p2 = max(random.sample(population, 5), key=lambda x: x.fitness)
            child = crossover(p1, p2)
            mutate(child, mutation_rate)
            child.calculate_fitness()
            new_pop.append(child)

        population = new_pop

    return population[0]

best_single_day_timetable = run_single_day_ga()

# Format and display the single-day timetable formatted by rooms
rows = []
for room in ROOMS:
    room_row = {'Room': room}
    for period in PERIODS:
        val = best_single_day_timetable.genes.get((period, room))
        if val is not None:
            klass, subject, teacher = val
            room_row[period] = f"{klass}\n{subject}\n({teacher})"
        else:
            room_row[period] = "-"
    rows.append(room_row)

df = pd.DataFrame(rows).set_index('Room')
print("\n--- OPTIMIZED SINGLE-DAY TIMETABLE ---")
display(df.style.set_properties(**{
    'white-space': 'pre-wrap',
    'text-align': 'center',
    'border': '1px solid black'
}))

